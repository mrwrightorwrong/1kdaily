/**
 * Reads the operator's key file and writes local env files without printing any
 * secret value.
 *
 *   apps/web/.env.local        runtime config (never contains the PAT)
 *   .env.migrate.local         Management API token + DB password, tooling only
 *
 * BVN and NIN are deliberately ignored: they never enter this repository,
 * these files, logs, or any client payload. Real identity numbers belong in the
 * verification vendor's system, not in application config.
 *
 * Usage: node tools/setup/env-from-keys.mjs <path-to-keys-file> [--force]
 */
import { readFileSync, writeFileSync, existsSync, chmodSync } from "node:fs";
import { randomBytes } from "node:crypto";

const [, , sourcePath, ...flags] = process.argv;
const force = flags.includes("--force");

if (!sourcePath) {
  console.error("usage: node tools/setup/env-from-keys.mjs <path-to-keys-file> [--force]");
  process.exit(1);
}

const raw = readFileSync(sourcePath, "utf8").replace(/^\uFEFF/, "");

const FIELDS = [
  { key: "dbPassword", pattern: /^DB\s*Password\s*:?\s*/i },
  { key: "url", pattern: /^Supabase\s*Url\s*:?\s*/i },
  { key: "anonKey", pattern: /^Anon\s*Key\s*:?\s*/i },
  { key: "serviceKey", pattern: /^Service\s*Role\s*Key\s*:?\s*/i },
  { key: "accessToken", pattern: /^Access\s*Tok(?:en|in)\s*:?\s*/i },
  { key: "email", pattern: /^[A-Za-z/ ]*Email\s*:?\s*/i },
  { key: "bvn", pattern: /^BVN\s*:?\s*/i },
  { key: "nin", pattern: /^NIN\s*:?\s*/i },
];

const parsed = {};
const unknown = [];

for (const line of raw.split(/\r?\n/)) {
  const trimmed = line.trim();
  if (!trimmed) continue;
  const field = FIELDS.find((candidate) => candidate.pattern.test(trimmed));
  if (!field) {
    unknown.push(trimmed.slice(0, 24));
    continue;
  }
  // Identity numbers are acknowledged, never retained.
  if (field.key === "bvn" || field.key === "nin") {
    parsed[field.key] = "<ignored>";
    continue;
  }
  parsed[field.key] = trimmed.replace(field.pattern, "").trim();
}

const { url, anonKey, serviceKey, dbPassword, accessToken } = parsed;

if (!url || !anonKey || !serviceKey) {
  console.error("Missing Supabase URL / anon key / service key in the source file.");
  process.exit(1);
}

const runtimeTarget = "apps/web/.env.local";
const toolingTarget = ".env.migrate.local";

const existingRuntime = existsSync(runtimeTarget) ? readFileSync(runtimeTarget, "utf8") : "";
const existingPepper = existingRuntime.match(/^KYC_HASH_PEPPER=(.+)$/m)?.[1]?.trim();
const pepper = existingPepper ?? randomBytes(32).toString("base64url");

const projectRef = new URL(url).hostname.split(".")[0];

const runtime = `# 1kDaily local runtime secrets — NEVER commit.
# Generated by tools/setup/env-from-keys.mjs on ${new Date().toISOString()}.
# The service-role key bypasses RLS: server code only, never a NEXT_PUBLIC_ variable.
# BVN/NIN are intentionally absent. Identity numbers are never stored in config.

NEXT_PUBLIC_SUPABASE_URL=${url}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
NEXT_PUBLIC_SITE_URL=${process.env.NEXT_PUBLIC_SITE_URL ?? "http://localhost:3000"}
SUPABASE_SERVICE_ROLE_KEY=${serviceKey}

# Server-only HMAC pepper used to detect duplicate identity documents without
# storing the identifier itself. Rotating this invalidates duplicate detection.
KYC_HASH_PEPPER=${pepper}

# Local development uses the deterministic mock provider. It stores nothing.
KYC_PROVIDER=mock
KYC_MOCK_AUTO_VERIFY=true
`;

const tooling = `# Migration / tooling credentials — NEVER commit, NEVER expose to the app.
# Used by tools/db/*.mjs. The access token is a Supabase personal access token.
SUPABASE_ACCESS_TOKEN=${accessToken ?? ""}
SUPABASE_PROJECT_REF=${projectRef}
${dbPassword ? `SUPABASE_DB_PASSWORD=${dbPassword}\n` : ""}`;

if (existsSync(runtimeTarget) && !force) {
  writeFileSync(`${runtimeTarget}.bak`, existingRuntime, "utf8");
}

writeFileSync(runtimeTarget, runtime, { encoding: "utf8", mode: 0o600 });
writeFileSync(toolingTarget, tooling, { encoding: "utf8", mode: 0o600 });
for (const file of [runtimeTarget, toolingTarget]) {
  try {
    chmodSync(file, 0o600);
  } catch {
    /* advisory on Windows */
  }
}

console.log(`Wrote ${runtimeTarget}`);
console.log(`  NEXT_PUBLIC_SUPABASE_URL        ${url}`);
console.log(`  NEXT_PUBLIC_SUPABASE_ANON_KEY   <redacted ${anonKey.length} chars>`);
console.log(`  SUPABASE_SERVICE_ROLE_KEY       <redacted ${serviceKey.length} chars>`);
console.log(`  KYC_HASH_PEPPER                 <generated ${pepper.length} chars>`);
console.log(`Wrote ${toolingTarget}`);
console.log(`  SUPABASE_ACCESS_TOKEN           ${accessToken ? `<redacted ${accessToken.length} chars>` : "<missing>"}`);
console.log(`  SUPABASE_PROJECT_REF            ${projectRef}`);
console.log(`  SUPABASE_DB_PASSWORD            ${dbPassword ? "<redacted>" : "<missing>"}`);
console.log(`  BVN / NIN                       <ignored by design>`);
if (unknown.length) console.log(`Ignored ${unknown.length} unrecognised line(s).`);
console.log("\nVerify: git status must not list either env file.");
